/* global console, process */
// WCAG contrast check for the design tokens. Plain Node ESM, no dependencies.
// Usage: node scripts/contrast.mjs   (exit 1 when a threshold is missed)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(resolve(here, "../src/ds/tokens.css"), "utf8");

function block(startRe) {
  const m = startRe.exec(css);
  if (!m) throw new Error(`block not found: ${startRe}`);
  const open = css.indexOf("{", m.index);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) return css.slice(open + 1, i);
  }
  throw new Error("unterminated block");
}
function hexVars(body) {
  const out = {};
  for (const m of body.matchAll(/(--[\w-]+)\s*:\s*(#[0-9a-fA-F]{6})\b/g)) out[m[1]] = m[2];
  return out;
}
const themes = {
  light: hexVars(block(/^:root\s*\{/m)),
  dark: hexVars(block(/^:root\[data-theme="dark"\]\s*\{/m)),
};

const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const lin = (c) => ((c /= 255) <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (c) => { const [r, g, b] = c.map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const mix = (fg, bg, a) => fg.map((v, i) => v * a + bg[i] * (1 - a));
const hex = (c) => "#" + c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("").toUpperCase();

const surfaces = ["--sheet", "--raised", "--sunk", "--pen-soft"];
const rows = [];
let failed = 0;
function add(theme, group, fgName, bgName, fg, bg, min, informational = false) {
  const r = ratio(fg, bg);
  const ok = informational || r >= min;
  if (!ok) failed++;
  rows.push({ theme, group, fgName, bgName, r, min, ok, informational });
}

for (const [theme, t] of Object.entries(themes)) {
  const c = (n) => { if (!t[n]) throw new Error(`${theme}: missing ${n}`); return rgb(t[n]); };
  for (const fg of ["--fg", "--fg-muted", "--warn", "--danger", "--ok", "--pen"])
    for (const bg of surfaces) add(theme, "text", fg, bg, c(fg), c(bg), 4.5);
  add(theme, "text", "--pen-fg", "--pen", c("--pen-fg"), c("--pen"), 4.5);
  add(theme, "text", "--pen-fg", "--pen-hover", c("--pen-fg"), c("--pen-hover"), 4.5);
  // Disabled secondary button: whole control at opacity 0.5 over its surface (ds.css .ds-btn:disabled).
  for (const bg of ["--raised", "--sheet"]) {
    const dis = mix(c("--fg"), c(bg), 0.5);
    add(theme, "disabled", `--fg @50% (${hex(dis)})`, bg, dis, c(bg), 3);
    const en = ratio(c("--fg"), c(bg)), di = ratio(dis, c(bg));
    const ok = en / di >= 1.3;
    if (!ok) failed++;
    rows.push({ theme, group: "disabled", fgName: "enabled/disabled ratio", bgName: bg, r: en / di, min: 1.3, ok, ratioOfRatios: true });
  }
  // Disabled primary: --fg-muted text, dashed --edge outline, transparent fill.
  for (const bg of ["--sheet", "--raised"]) {
    add(theme, "disabled", "--fg-muted (primary disabled)", bg, c("--fg-muted"), c(bg), 3);
    add(theme, "disabled", "--edge dashed outline", bg, c("--edge"), c(bg), 3);
  }
  // Outlined danger button ("Stop after trial", run.css .run-stop): --danger label on the --raised button fill (was a filled button before the pass 3 layout pass; threshold unchanged).
  add(theme, "text", "--danger (Stop after trial, outlined)", "--raised", c("--danger"), c("--raised"), 4.5);
  // Chart text: axis ticks, legend and axis names sit on the chart sheet (--raised); literals come from useEChart/theme.ts mapping.
  const chartText = theme === "light" ? { axis: "#3E4C57", legend: "#0E1A22" } : { axis: "#8B94A0", legend: "#E6E8EB" };
  for (const [n, h] of Object.entries(chartText)) add(theme, "chart", `chart ${n} text (${h})`, "--raised", rgb(h), c("--raised"), 4.5);
  for (const bg of surfaces) add(theme, "focus", "--pen ring", bg, c("--pen"), c(bg), 3);
  for (const bg of surfaces) add(theme, "border", "--edge", bg, c("--edge"), c(bg), 3);
  for (const bg of surfaces) add(theme, "grid", "--grid", bg, c("--grid"), c(bg), 0, true);
}

const unit = (x) => (x.ratioOfRatios ? "x" : ":1");
const lines = rows.map((x) =>
  `${x.theme.padEnd(5)} ${x.group.padEnd(8)} ${x.fgName.padEnd(34)} on ${x.bgName.padEnd(11)} ${x.r.toFixed(2).padStart(5)}${unit(x)}  ${x.informational ? "info" : `>=${x.min}`.padEnd(5)} ${x.informational ? "" : x.ok ? "PASS" : "FAIL"}`);
console.log(lines.join("\n"));
console.log(`\n${failed === 0 ? "All contrast thresholds met." : `${failed} pair(s) below threshold.`}`);

const md = ["# Contrast ratios (generated by app/scripts/contrast.mjs)", "",
  "Hex fallback tokens from `app/src/ds/tokens.css`. Thresholds: text 4.5, UI/disabled/focus/border 3. Grid is informational.", ""];
for (const theme of Object.keys(themes)) {
  md.push(`## ${theme}`, "", "| Group | Foreground | Background | Ratio | Min | Result |", "|---|---|---|---|---|---|");
  for (const x of rows.filter((r) => r.theme === theme))
    md.push(`| ${x.group} | ${x.fgName} | ${x.bgName} | ${x.r.toFixed(2)}${unit(x)} | ${x.informational ? "info" : x.min} | ${x.informational ? "-" : x.ok ? "pass" : "FAIL"} |`);
  md.push("");
}
const out = resolve(here, `../../.ui-overhaul/${process.env.REVIEW ?? "review4"}/contrast.md`);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, md.join("\n"));
process.exit(failed ? 1 : 0);
